// Phone alerts (web push) for the 2nd Chance portals. Shows the alert and opens the right page when it is tapped.
// No offline caching: this file only handles alerts (the site always loads fresh from the server).
self.addEventListener("install", () => self.skipWaiting());
self.addEventListener("activate", (e) => e.waitUntil(self.clients.claim()));
self.addEventListener("push", (e) => {
  let d = {};
  try { d = e.data ? e.data.json() : {}; } catch (err) { d = { body: e.data ? e.data.text() : "" }; }
  e.waitUntil(self.registration.showNotification(d.title || "2nd Chance Housing", {
    body: d.body || "", icon: "/logo-192.png", badge: "/logo-192.png", tag: d.tag || "alert", renotify: true, requireInteraction: true,
    data: { url: d.url || "/resident/" },
  }));
});
self.addEventListener("notificationclick", (e) => {
  e.notification.close();
  const url = new URL((e.notification.data && e.notification.data.url) || "/resident/", self.location.origin).href;
  e.waitUntil(self.clients.matchAll({ type: "window", includeUncontrolled: true }).then((cs) => {
    for (const c of cs) if (c.url.split("#")[0] === url.split("#")[0] && "focus" in c) { c.navigate(url); return c.focus(); }
    return self.clients.openWindow(url);
  }));
});
