-- Human Mirror database #3: Milwaukee Cost-of-Living Benchmarks (the published prices behind the Daily Number).
-- Built 11/14/2026 from Milwaukee_Cost_of_Living_Benchmarks_v0.3 ("_use" copy, research date 11/13/2026), at Stephen's request
-- ("build them please"). Stephen chose (11/14/2026): show the benchmarks beside each cost on the Daily Number pages.
--   * mirror.cost_benchmarks: 144 rows (benchmark_id COL-001 ...), category = one of the 12 Daily Number cost categories, level =
--     survival / stability / aspirational, the price as published plus the per-month and per-day figures and the workbook's formula.
--   * mirror.cost_benchmark_sources (COL-S..), mirror.cost_benchmark_examples (sums of published rows), mirror.cost_benchmark_conflicts.
--   * mirror.cost_benchmarks_get(): signed-in users only. A person (and their coordinator) gets only rows that are "Verified" and carry a
--     figure; office staff and Housing Navigators also get the rows still being checked (Needs Confirmation, Unverified Lead) and the conflicts.
-- Nothing here changes a person's Daily Number: the page offers "Use this amount" and the person saves the cost themselves.
-- The data is loaded by 20261119751000 (generated by tools/cost-benchmarks-import.mjs); a newer workbook replaces the rows (reference data,
-- not edited by the office). New tables carry explicit grants (CLAUDE.md, 10/30/2026): service_role only; row security on.

create table mirror.cost_benchmark_sources (
  source_id text primary key,
  title text not null,
  url text,
  source_type text,
  date_accessed date,
  source_date text
);

create table mirror.cost_benchmarks (
  benchmark_id text primary key,
  category text not null references mirror.expense_categories(key),
  item text not null,
  short_label text not null,
  level text not null check (level in ('survival', 'stability', 'aspirational')),
  household_size text not null,
  amount_as_published numeric,
  unit text,
  frequency text,
  one_time_amount numeric,
  per_year numeric,
  per_month numeric,
  per_day numeric,
  formula text,
  geography text,
  as_of_date text,
  poverty_premium boolean not null default false,
  cheaper_alternative text,
  verification_status text not null check (verification_status in ('Verified - Current', 'Verified - Limited', 'Needs Confirmation', 'Unverified Lead')),
  source_ids text[] not null default '{}',
  sort int not null,
  import_version text not null,
  imported_at timestamptz not null default now()
);
create index cost_benchmarks_cat on mirror.cost_benchmarks (category, level);

create table mirror.cost_benchmark_examples (
  id int primary key,
  household_size text not null,
  level text not null check (level in ('survival', 'stability', 'aspirational')),
  total_per_year numeric, total_per_month numeric, total_per_day numeric,
  one_time_note text,
  benchmark_ids text[] not null default '{}',
  note text
);

create table mirror.cost_benchmark_conflicts (
  id int primary key,
  benchmark_id text not null,
  value_a text, source_a text, value_b text, source_b text,
  note text
);

alter table mirror.cost_benchmark_sources enable row level security;
alter table mirror.cost_benchmarks enable row level security;
alter table mirror.cost_benchmark_examples enable row level security;
alter table mirror.cost_benchmark_conflicts enable row level security;
revoke all on mirror.cost_benchmark_sources, mirror.cost_benchmarks, mirror.cost_benchmark_examples, mirror.cost_benchmark_conflicts
  from public, anon, authenticated;
grant select, insert, update, delete on mirror.cost_benchmark_sources, mirror.cost_benchmarks, mirror.cost_benchmark_examples,
  mirror.cost_benchmark_conflicts to service_role;

-- The benchmarks for the Daily Number pages. Any signed-in user; people see only verified rows with a figure.
create or replace function public.mirror_cost_benchmarks() returns jsonb
language plpgsql stable security definer set search_path = mirror, public as $$
declare v_office boolean;
begin
  if auth.email() is null then raise exception 'Please sign in.' using errcode = '42501'; end if;
  v_office := coalesce(public.chpms_role(), '') in ('staff', 'navigator', 'navigator_preview');
  return jsonb_build_object(
    'version', (select max(import_version) from mirror.cost_benchmarks),
    'office', v_office,
    'rows', coalesce((select jsonb_agg(jsonb_build_object('id', b.benchmark_id, 'category', b.category, 'item', b.item, 'label', b.short_label,
        'level', b.level, 'household', b.household_size, 'amount', b.amount_as_published, 'unit', b.unit, 'frequency', b.frequency,
        'one_time', b.one_time_amount, 'per_month', b.per_month, 'per_day', b.per_day, 'formula', b.formula, 'geography', b.geography,
        'as_of', b.as_of_date, 'poverty_premium', b.poverty_premium, 'cheaper', b.cheaper_alternative, 'status', b.verification_status,
        'sources', b.source_ids) order by b.sort)
      from mirror.cost_benchmarks b
     where v_office or (b.verification_status like 'Verified%' and (b.amount_as_published is not null))), '[]'::jsonb),
    'sources', coalesce((select jsonb_object_agg(s.source_id, jsonb_build_object('title', s.title, 'url', s.url, 'type', s.source_type,
        'accessed', s.date_accessed, 'date', s.source_date)) from mirror.cost_benchmark_sources s), '{}'::jsonb),
    'examples', coalesce((select jsonb_agg(to_jsonb(e) order by e.id) from mirror.cost_benchmark_examples e), '[]'::jsonb),
    'conflicts', case when v_office then coalesce((select jsonb_agg(to_jsonb(c) order by c.id) from mirror.cost_benchmark_conflicts c), '[]'::jsonb)
                 else '[]'::jsonb end);
end $$;

revoke all on function public.mirror_cost_benchmarks() from public, anon;
grant execute on function public.mirror_cost_benchmarks() to authenticated, service_role;
