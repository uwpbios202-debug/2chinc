// The Human Mirror Phase 5: seed for the 11 functional areas (question sets of kind 'functional') and the 7 living options.
// Source: site/mirror/assets/functional-data.js and site/mirror/assets/living-options.js (the same files the pages use).
// Generates the migration:  node tools/mirror-checks/phase5-seed.mjs > supabase/migrations/20261119301000_mirror_functional_housing_seed.sql
// Changing wording later: change the data file and generate a NEW migration (the question-version trigger keeps the old wording).

import { AREAS, areaQuestions } from "../../site/mirror/assets/functional-data.js";
import { OPTIONS } from "../../site/mirror/assets/living-options.js";

const lit = (s) => (s == null ? "null" : "'" + String(s).replace(/'/g, "''") + "'");
const opts = (pairs) => (pairs ? JSON.stringify(pairs.map(([value, label]) => ({ value, label }))) : "[]");

const sets = AREAS.map((a, i) => `  (${lit("functional_" + a.key)}, ${lit(a.title)}, ${lit(a.intro)}, ${(i + 1) * 10})`);
const qs = [];
for (const a of AREAS) {
  areaQuestions(a).forEach(([key, type, prompt, help, options], j) => {
    qs.push(`  (${lit("functional_" + a.key)}, ${lit(key)}, ${lit(prompt)}, ${lit(help)}, ${lit(type)}, ${lit(opts(options))}::jsonb, ${lit(a.category)}, ${(j + 1) * 10})`);
  });
}
const options = OPTIONS.map((o, i) => `  (${lit(o.key)}, ${(i + 1) * 10}, ${lit(o.title)}, ${lit(o.summary)}, ${lit(JSON.stringify({ what: o.what, support: o.support, who: o.who, pay: o.pay, ask: o.ask }))}::jsonb)`);

console.log(`-- The Human Mirror Phase 5 seed. GENERATED by tools/mirror-checks/phase5-seed.mjs (edit the data files, never this file).
-- ${AREAS.length} functional areas (question sets of kind 'functional', reflection 'function'), ${qs.length} questions (5 each), ${OPTIONS.length} living options.
-- Topics: ${AREAS.map((a) => a.key + " " + a.category).join(", ")}. Every question is optional; never a diagnosis (prompt Part 5).

insert into mirror.question_sets (key, kind, reflection_key, title, intro, sort)
select v.key, 'functional', 'function', v.title, v.intro, v.sort
from (values
${sets.join(",\n")}
) v(key, title, intro, sort)
on conflict (key) do nothing;

insert into mirror.reflection_questions (set_id, key, prompt, help, answer_type, options, category, sort)
select s.id, v.key, v.prompt, v.help, v.answer_type, v.options, v.category, v.sort
from (values
${qs.join(",\n")}
) v(set_key, key, prompt, help, answer_type, options, category, sort)
join mirror.question_sets s on s.key = v.set_key
on conflict (set_id, key) do nothing;

insert into mirror.housing_options (key, sort, title, summary, description)
values
${options.join(",\n")}
on conflict (key) do nothing;`);
