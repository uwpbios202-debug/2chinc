// The Human Mirror T3.5: one question set per life dimension (15), each with the nine-question pattern of the Clothes paper
// (D-10: have / condition / missing / prefer / barriers / resources / skills / cost / sustain) plus "would you like help".
// Plain words; every question optional. Privacy: the whole set takes the dimension's sensitive category where it has one
// (physical health, mental health, ID and legal, money, safety); the cost question is always "financial" (D-14).
//
// node tools/mirror-checks/dimension-questions.mjs > supabase/migrations/<version>_mirror_dimension_questions.sql

/** key -> [topic phrase used inside questions, privacy category] */
const D = {
  housing: ["a place to live", "general"],
  physical_health: ["your physical health and health care", "health"],
  mental_health: ["how you feel inside", "mental_health"],
  identity_legal: ["your ID, papers and legal matters", "legal"],
  food: ["food and everyday basics", "general"],
  transportation: ["getting around", "general"],
  technology: ["your phone, internet and computer", "general"],
  work: ["school, work and your career", "general"],
  finances: ["money", "financial"],
  self_care: ["clothes, hygiene and taking care of yourself", "general"],
  relationships: ["family, friends and community", "general"],
  life_skills: ["everyday life skills like cooking, budgeting and keeping a home", "general"],
  safety: ["feeling safe", "safety"],
  development: ["your interests and the things you enjoy", "general"],
  purpose: ["your purpose and your future", "general"],
};

/** [key, type, prompt(topic), help, options, categoryOverride] */
const PATTERN = [
  ["have", "long_text", (t) => `When it comes to ${t}, what do you have right now?`, "Things, people, places, help you already get. Anything counts."],
  ["condition", "rating", (t) => `How well is it going with ${t} right now?`, "1 means very hard. 5 means very good."],
  ["missing", "long_text", (t) => `What's missing or not working when it comes to ${t}?`],
  ["prefer", "long_text", (t) => `If things went the way you'd like, what would ${t} look like for you?`],
  ["barriers", "long_text", () => "What gets in the way?", "For example cost, distance, paperwork, health, time, or not knowing where to start."],
  ["resources", "long_text", (t) => `Who or what already helps you with ${t}?`],
  ["skills", "long_text", () => "What do you already know or do well here, and what would you like to learn?"],
  ["cost", "money", (t) => `About how much do you spend on ${t} in a month?`, "A rough number is fine. Skip it if it doesn't apply.", null, "financial"],
  ["sustain", "long_text", () => "What would help you keep this part of life steady over time?"],
  ["help_wanted", "choice", () => "Would you like help with this part of your life?", "You can change this any time.",
    [{ value: "now", label: "Yes, now" }, { value: "later", label: "Maybe later" }, { value: "no", label: "No, thank you" }]],
];

const lit = (s) => (s == null ? "null" : "'" + String(s).replace(/'/g, "''") + "'");
const rows = [];
for (const [dim, [topic, cat]] of Object.entries(D)) {
  PATTERN.forEach(([key, type, prompt, help = null, options = null, catOverride = null], i) => {
    // Money spent on mental health or safety is still money: cost stays "financial"; help_wanted follows the area.
    rows.push(`  (${lit(dim)}, ${lit(key)}, ${lit(prompt(topic))}, ${lit(help)}, ${lit(type)}, ${lit(JSON.stringify(options || []))}::jsonb, ${lit(catOverride || cat)}, ${(i + 1) * 10})`);
  });
}

console.log(`-- The Human Mirror T3.5: the 15 life dimension question sets (${rows.length} questions). GENERATED by
-- tools/mirror-checks/dimension-questions.mjs (edit there, never by hand). Nine-question pattern of the Clothes paper (D-10)
-- plus "would you like help". Sensitive areas (physical health, mental health, ID/legal, money, safety) are private as a whole;
-- every cost question is "financial". Every question is optional.

insert into mirror.question_sets (key, kind, dimension_key, title, intro, sort)
select 'dimension_' || d.key, 'dimension', d.key, d.title, d.intro, d.n from mirror.dimensions d
on conflict (key) do nothing;

insert into mirror.reflection_questions (set_id, key, prompt, help, answer_type, options, category, sort)
select s.id, v.key, v.prompt, v.help, v.answer_type, v.options, v.category, v.sort
from (values
${rows.join(",\n")}
) v(dim, key, prompt, help, answer_type, options, category, sort)
join mirror.question_sets s on s.key = 'dimension_' || v.dim
on conflict (set_id, key) do nothing;`);
