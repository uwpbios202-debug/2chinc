const lit = (s) => (s == null ? "null" : "'" + String(s).replace(/'/g, "''") + "'");
const setRows = SETS.map(([key, n, title, intro]) => `  (${lit(key)}, ${lit(title)}, ${lit(intro)}, ${100 + n})`);
const qRows = [];
for (const [key, , , , cat, qs] of SETS) {
  qs.forEach(([qk, type, prompt, help = null, options = null, catOverride = null], i) => {
    qRows.push(`  (${lit(key)}, ${lit(qk)}, ${lit(prompt)}, ${lit(help)}, ${lit(type)}, ${lit(JSON.stringify(options || []))}::jsonb, ${lit(catOverride || cat)}, ${(i + 1) * 10})`);
  });
}
console.log(`-- The Human Mirror: the six Daily Number reflections (Stephen's Daily Number paper, section 6), ${qRows.length} questions.
-- GENERATED by tools/mirror-checks/dn-reflection-questions.mjs (edit there). Kind "module"; money questions "financial".

insert into mirror.question_sets (key, kind, title, intro, sort)
select v.key, 'module', v.title, v.intro, v.sort from (values
${setRows.join(",\n")}
) v(key, title, intro, sort)
on conflict (key) do nothing;

insert into mirror.reflection_questions (set_id, key, prompt, help, answer_type, options, category, sort)
select s.id, v.key, v.prompt, v.help, v.answer_type, v.options, v.category, v.sort
from (values
${qRows.join(",\n")}
) v(set_key, key, prompt, help, answer_type, options, category, sort)
join mirror.question_sets s on s.key = v.set_key
on conflict (set_id, key) do nothing;`);
